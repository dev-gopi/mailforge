/** Additional email-safe design presets. All tokens inherit from the existing modern contract. */
import { modernTheme } from "../default/modern.js";
import type { ResolvedEmailTheme, ThemeAppearance, ThemeColors, ThemePreset, ThemeSpacing, ThemeTypography } from "../contracts/Theme.types.js";

type NewTheme = Exclude<ThemePreset, "modern" | "minimal" | "corporate">;

function professionalPreset(name: NewTheme, palette: ThemeColors, typography: Partial<ThemeTypography>, appearance: Partial<ThemeAppearance>, spacing: ThemeSpacing): ResolvedEmailTheme {
    return {
        ...modernTheme,
        preset: name,
        colors: { ...modernTheme.colors, ...palette },
        typography: { ...modernTheme.typography, ...typography },
        appearance: { ...modernTheme.appearance, ...appearance },
        spacing: { ...modernTheme.spacing, ...spacing },
    };
}

