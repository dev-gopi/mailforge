import { createEmail, type MailForgeEmail } from "../../packages/email/src/index.js";
import { type RenderResult } from "../../packages/core/src/index.js";
import { inspectEmailQuality, type EmailQualityReport } from "../../packages/preview/src/index.js";

export interface WelcomeEmailData {
  recipientName: string;
  recipientEmail: string;
  actionUrl: string;
}

export interface InvoiceItem {
  name: string;
  quantity: number;
  unitPriceCents: number;
}

export interface InvoiceEmailData {
  customerName: string;
  invoiceNumber: string;
  issuedOn: string;
  dueOn: string;
  currency: string;
  items: InvoiceItem[];
  paymentUrl: string;
}

export interface RenderedEmailOutput extends RenderResult {
  quality: EmailQualityReport;
}

/**
 * Type-safe MailForge client demonstration.
 */
export class TypedMailForgeService {
  private readonly engine: MailForgeEmail;

  constructor(appName = "TypeScript Enterprise App") {
    this.engine = createEmail({
      brand: {
        name: appName,
        primaryColor: "#2563eb",
        website: "https://example.com",
        supportEmail: "support@example.com",
      },
      theme: "modern",
      footer: {
        message: "This email was generated by a type-safe TypeScript MailForge pipeline.",
      },
    });
  }

  /**
   * Renders a fully validated and typed welcome email.
   */
  async renderWelcome(payload: WelcomeEmailData): Promise<RenderedEmailOutput> {
    const result = await this.engine.render("welcome", {
      data: {
        user: { firstName: payload.recipientName },
        actionUrl: payload.actionUrl,
      },
    });

    const quality = inspectEmailQuality(result.html);
    return { ...result, quality };
  }

  /**
   * Renders a structured, validated invoice email.
   */
  async renderInvoice(payload: InvoiceEmailData): Promise<RenderedEmailOutput> {
    const result = await this.engine.render("invoice", {
      data: {
        customer: { name: payload.customerName },
        invoice: {
          number: payload.invoiceNumber,
          issuedOn: payload.issuedOn,
          dueOn: payload.dueOn,
          currency: payload.currency,
          items: payload.items,
          shippingCents: 0,
          discountCents: 0,
        },
        paymentUrl: payload.paymentUrl,
      },
    });

    const quality = inspectEmailQuality(result.html);
    return { ...result, quality };
  }
}

/**
 * Runner function demonstrating typed execution.
 */
export async function runTypescriptExample(): Promise<void> {
  console.log("Starting MailForge TypeScript Type-Safe Rendering...");
  const service = new TypedMailForgeService("MailForge TS Suite");

  // 1. Render Welcome
  const welcome = await service.renderWelcome({
    recipientName: "Morgan Vance",
    recipientEmail: "morgan@example.com",
    actionUrl: "https://app.example.com/onboarding",
  });

  console.log("\n[TypeScript] Welcome Email Rendered:");
  console.log(`  Subject: ${welcome.subject}`);
  console.log(`  Size: ${welcome.quality.sizeKb} KB`);
  console.log(`  Score: ${welcome.quality.score}/100`);

  // 2. Render Invoice
  const invoice = await service.renderInvoice({
    customerName: "Acme Dynamics",
    invoiceNumber: "INV-TS-2026",
    issuedOn: "2026-10-14",
    dueOn: "2026-10-31",
    currency: "USD",
    items: [
      { name: "Enterprise Dedicated Cluster", quantity: 1, unitPriceCents: 99000 },
      { name: "24/7 SLA Support", quantity: 1, unitPriceCents: 25000 },
    ],
    paymentUrl: "https://pay.example.com/invoice/INV-TS-2026",
  });

  console.log("\n[TypeScript] Invoice Email Rendered:");
  console.log(`  Subject: ${invoice.subject}`);
  console.log(`  Size: ${invoice.quality.sizeKb} KB`);
  console.log(`  Plain Text lines: ${invoice.text.split("\n").length}`);

  console.log("\nTypeScript execution completed with full type safety.");
}

// CLI Execution with tsx
runTypescriptExample().catch((err) => {
  console.error("TypeScript example error:", err);
  process.exit(1);
});
